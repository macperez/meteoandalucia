-- PostgreSQL: estructura del inventario exportado en data/estaciones.csv.
-- Crea las tablas en una base nueva o en un esquema sin estas tablas.
-- No modifica ni migra la tabla aemet.station del antiguo meteobackup.sql.
-- Incluye el catálogo de comunidades; no ejecutar comunidades_ddl.sql adicionalmente.
-- El CSV no contiene la CCAA: se relaciona mediante el catálogo de provincias.

BEGIN;

CREATE SCHEMA IF NOT EXISTS aemet;

-- PostgreSQL: catálogo de comunidades y ciudades autónomas.

CREATE TABLE public.comunidades (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    comunidad text NOT NULL UNIQUE,
    CONSTRAINT comunidades_slug_check CHECK (btrim(slug) <> ''),
    CONSTRAINT comunidades_nombre_check CHECK (btrim(comunidad) <> '')
);




CREATE TABLE public.provincia (
    -- Código oficial de provincia; se asigna explícitamente, no es autonumérico.
    id smallint PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    provincia text NOT NULL UNIQUE,
    comunidad_id integer NOT NULL,
    CONSTRAINT provincia_comunidad_fk FOREIGN KEY (comunidad_id)
        REFERENCES public.comunidades (id),
    CONSTRAINT provincia_id_check CHECK (id BETWEEN 1 AND 52),
    CONSTRAINT provincia_slug_check CHECK (btrim(slug) <> ''),
    CONSTRAINT provincia_nombre_check CHECK (btrim(provincia) <> '')
);

CREATE INDEX provincia_comunidad_id_idx ON public.provincia (comunidad_id);

CREATE TABLE aemet.station (
    indicativo text PRIMARY KEY,
    nombre text NOT NULL,
    provincia_id smallint NOT NULL,
    altitud integer NOT NULL,
    latitud varchar(7) NOT NULL,
    longitud varchar(7) NOT NULL,
    -- Es opcional en el inventario y puede tener ceros iniciales.
    indsinop text,
    CONSTRAINT station_provincia_fk FOREIGN KEY (provincia_id)
        REFERENCES public.provincia (id),
    CONSTRAINT station_indicativo_check CHECK (btrim(indicativo) <> ''),
    CONSTRAINT station_nombre_check CHECK (btrim(nombre) <> ''),
    -- Se conserva el dato original: MARBELLA (6083X) incluye 362860N.
    -- Se valida el formato, sin rechazar los segundos 60 del inventario.
    CONSTRAINT station_latitud_check CHECK (latitud ~ '^[0-9]{6}[NS]$'),
    CONSTRAINT station_longitud_check CHECK (
        longitud ~ '^[0-9]{6}[EW]$'
    ),
    CONSTRAINT station_indsinop_check CHECK (indsinop ~ '^[0-9]{5}$')
);

CREATE INDEX station_provincia_id_idx ON aemet.station (provincia_id);

COMMENT ON COLUMN aemet.station.altitud IS 'Altitud en metros sobre el nivel del mar.';
COMMENT ON COLUMN aemet.station.latitud IS 'Formato AEMET: DDMMSS seguido de N o S.';
COMMENT ON COLUMN aemet.station.longitud IS 'Formato AEMET del CSV: DDMMSS seguido de E o W.';
COMMENT ON COLUMN aemet.station.indsinop IS 'Indicativo sinóptico; NULL si el CSV lo deja vacío.';

-- Mapeo de importación: CSV.provincia -> provincia.provincia -> station.provincia_id.
-- El resto de campos conserva los nombres de las cabeceras del CSV.
-- Consulta equivalente al CSV original:
-- SELECT s.indicativo, s.nombre, p.provincia, s.altitud,
--        s.latitud, s.longitud, s.indsinop
-- FROM aemet.station AS s
-- JOIN public.provincia AS p ON p.id = s.provincia_id;

-- Entrada de ficheros CSV AEMET antes de cualquier transformación SQL.
CREATE SCHEMA IF NOT EXISTS raw;

-- Los 27 campos originales, todos text y sin restricciones de calidad o unicidad.
-- La carga raw debe admitir vacíos, duplicados y anomalías del proveedor.
CREATE TABLE raw.aemet_measurement (
    fecha text,
    indicativo text,
    nombre text,
    provincia text,
    altitud text,
    tmed text,
    prec text,
    tmin text,
    horatmin text,
    tmax text,
    horatmax text,
    "hrMedia" text,
    "hrMax" text,
    "horaHrMax" text,
    "hrMin" text,
    "horaHrMin" text,
    "pintMax" text,
    "horaPIntMax" text,
    dir text,
    velmedia text,
    racha text,
    horaracha text,
    "presMax" text,
    "horaPresMax" text,
    "presMin" text,
    "horaPresMin" text,
    sol text
);

COMMENT ON TABLE raw.aemet_measurement IS
    'Carga textual de los CSV diarios AEMET. El tipado, limpieza y deduplicación se realizarán después mediante SQL.';

-- Para COPY: indicar explícitamente las columnas en el orden de la cabecera de cada CSV.
-- HEADER descarta la primera línea, pero no relaciona nombres con columnas.
-- Los CSV pueden tener campos y orden distintos: no usar COPY sin lista de columnas.
-- Usar FORMAT csv, HEADER true, ENCODING 'UTF8' y FORCE_NOT_NULL con la lista
-- de columnas cargadas para preservar vacíos como texto vacío, sin convertirlos a NULL.
-- No transformar comas decimales, fechas, Ip, Acum, Varias ni horas durante la carga.
-- Destino tipado de las medidas diarias.
-- numeric sin escala fija conserva los decimales originales sin redondeo.
-- Las marcas no convertibles quedan NULL; el original se conserva en raw.
CREATE TABLE aemet.daily_measurement (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    indicativo text NOT NULL,
    fecha date NOT NULL,
    nombre text,
    provincia text,
    altitud integer,
    tmed numeric,
    prec numeric,
    tmin numeric,
    horatmin time without time zone,
    tmax numeric,
    horatmax time without time zone,
    "hrMedia" smallint,
    "hrMax" smallint,
    "horaHrMax" time without time zone,
    "hrMin" smallint,
    "horaHrMin" time without time zone,
    "pintMax" numeric,
    "horaPIntMax" time without time zone,
    dir smallint,
    velmedia numeric,
    racha numeric,
    horaracha time without time zone,
    "presMax" numeric,
    "horaPresMax" smallint,
    "presMin" numeric,
    "horaPresMin" smallint,
    sol numeric,
    CONSTRAINT daily_measurement_station_fk FOREIGN KEY (indicativo)
        REFERENCES aemet.station (indicativo)
);

CREATE INDEX daily_measurement_fecha_idx ON aemet.daily_measurement (fecha);
COMMENT ON TABLE aemet.daily_measurement IS
    'Medidas diarias tipadas; una fila por estaci?n y fecha, despu?s de deduplicar raw.';
COMMENT ON COLUMN aemet.daily_measurement."horaPresMax" IS
    'Hora entera original, incluidos 00 y 24; NULL cuando no hay una hora ?nica.';
COMMENT ON COLUMN aemet.daily_measurement."horaPresMin" IS
    'Hora entera original, incluidos 00 y 24; NULL cuando no hay una hora ?nica.';
COMMENT ON COLUMN aemet.daily_measurement.dir IS
    'C?digo de direcci?n original de AEMET; se conserva sin convertir a grados.';
COMMENT ON COLUMN aemet.daily_measurement.nombre IS
    'Nombre de la estaci?n en el CSV de medidas; conserva el dato hist?rico.';
COMMENT ON COLUMN aemet.daily_measurement.provincia IS
    'Nombre de provincia en el CSV; el cat?logo se consulta mediante station.provincia_id.';

COMMIT;
