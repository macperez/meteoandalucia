-- PostgreSQL: definiciones comunes. Ejecutar una vez antes de los DDL
-- de proveedores y de los inserts de catalogos. No es una migracion.
BEGIN;

CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE public.comunidades (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    comunidad text NOT NULL UNIQUE,
    CONSTRAINT comunidades_slug_check CHECK (btrim(slug) <> ''),
    CONSTRAINT comunidades_nombre_check CHECK (btrim(comunidad) <> '')
);




CREATE TABLE public.provincia (
    -- Código oficial de provincia; se asigna explícitamente, no es autonumérico.
    id smallint PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    provincia text NOT NULL UNIQUE,
    comunidad_id integer NOT NULL,
    CONSTRAINT provincia_comunidad_fk FOREIGN KEY (comunidad_id)
        REFERENCES public.comunidades (id),
    CONSTRAINT provincia_id_check CHECK (id BETWEEN 1 AND 52),
    CONSTRAINT provincia_slug_check CHECK (btrim(slug) <> ''),
    CONSTRAINT provincia_nombre_check CHECK (btrim(provincia) <> '')
);

CREATE INDEX provincia_comunidad_id_idx ON public.provincia (comunidad_id);

-- Una fila por medida y regla incumplida; sospecha no equivale a error.
CREATE TABLE public.control_medida (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    fecha_observacion date,
    variable text NOT NULL CHECK (btrim(variable) <> ''),
    valor text,
    estacion_id text NOT NULL CHECK (btrim(estacion_id) <> ''),
    provincia_id smallint REFERENCES public.provincia (id),
    esquema_origen text NOT NULL CHECK (btrim(esquema_origen) <> ''),
    tabla_origen text NOT NULL CHECK (btrim(tabla_origen) <> ''),
    registro_origen_id text NOT NULL CHECK (btrim(registro_origen_id) <> ''),
    regla text NOT NULL CHECK (btrim(regla) <> ''),
    causa_sospecha text NOT NULL CHECK (btrim(causa_sospecha) <> ''),
    estado_revision text NOT NULL DEFAULT 'pendiente'
        CHECK (estado_revision IN ('pendiente', 'dato_valido', 'error_confirmado')),
    fecha_deteccion timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT control_medida_origen_regla_uk UNIQUE (
        esquema_origen, tabla_origen, registro_origen_id, variable, regla
    )
);

CREATE INDEX control_medida_revision_fecha_idx
    ON public.control_medida (estado_revision, fecha_observacion);
CREATE INDEX control_medida_estacion_fecha_idx
    ON public.control_medida (esquema_origen, estacion_id, fecha_observacion);
CREATE INDEX control_medida_provincia_id_idx
    ON public.control_medida (provincia_id);

COMMENT ON TABLE public.control_medida IS
    'Sospechas de calidad compartidas entre fuentes y capas; no modifica ni invalida observaciones automaticamente.';
COMMENT ON COLUMN public.control_medida.valor IS
    'Valor examinado como texto para admitir errores de formato; NULL si falta.';
COMMENT ON COLUMN public.control_medida.fecha_observacion IS
    'Fecha de la medida; NULL si falta o no puede interpretarse.';
COMMENT ON COLUMN public.control_medida.estacion_id IS
    'Identificador original; en RIAweb se interpreta junto con provincia_id.';
COMMENT ON COLUMN public.control_medida.provincia_id IS
    'Codigo del catalogo comun; NULL si se desconoce. Consultar el nombre en public.provincia.';
COMMENT ON COLUMN public.control_medida.registro_origen_id IS
    'Referencia logica sin FK: id textual o clave compuesta serializada de forma estable, por ejemplo un array JSON. En raw sin id, definir una clave reproducible antes de registrar sospechas.';
COMMENT ON COLUMN public.control_medida.regla IS
    'Codigo estable de comprobacion. Usar INSERT ON CONFLICT DO NOTHING para evitar duplicados sin sobrescribir revisiones.';
COMMENT ON COLUMN public.control_medida.fecha_deteccion IS
    'Instante de la primera deteccion registrada.';

COMMIT;
