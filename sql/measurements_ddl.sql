-- PostgreSQL: tablas de medidas AEMET y tablas RIAweb para una base nueva.
-- Ejecutar después de aemet_ddl.sql y de cargar comunidades y provincias.
-- Conserva los nombres de columnas del esquema histórico; no importa el backup.
BEGIN;
CREATE SCHEMA IF NOT EXISTS meteo;

CREATE TABLE aemet.daily_measurement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id character varying(8) NOT NULL,
    measurement_date date NOT NULL,
    avg_temp real,
    precipitation real,
    min_temp real,
    time_mintemp character varying(8),
    max_temp real,
    time_maxtemp character varying(8),
    wind_direction real,
    avg_wind real,
    max_wind_speed real,
    time_maxwind character varying(8),
    max_press real,
    time_maxpress character varying(8),
    min_press real,
    time_minpress character varying(8)
);

CREATE TABLE meteo.provincias (
    code character varying(50),
    postal_code integer,
    name character varying(50),
    phone_code integer,
    iso2 character varying(50)
);

CREATE TABLE meteo.station (
    prov integer NOT NULL,
    station_code integer NOT NULL,
    station_name character varying(50),
    under_plastic boolean,
    active boolean,
    visible boolean,
    longitude text,
    latitude text,
    altitude integer,
    xutm double precision,
    yutm double precision,
    huso integer
);

CREATE TABLE meteo.daily_measurement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prov_id integer NOT NULL,
    station_id integer NOT NULL,
    measurement_date date NOT NULL,
    max_temp real,
    min_temp real,
    avg_temp real,
    time_maxtemp character varying(5),
    time_mintemp character varying(5),
    max_humid real,
    min_humid real,
    avg_humid real,
    time_maxhumid character varying(5),
    time_minhumid character varying(5),
    wind_speed real,
    wind_direction real,
    max_wind_speed real,
    direction_max_wind real,
    time_maxwind character varying(5),
    radiation real,
    precipitation real,
    batery real,
    dateutlmod timestamp without time zone,
    et0 double precision
);

ALTER TABLE aemet.daily_measurement
    ADD CONSTRAINT daily_measurement_unique UNIQUE (station_id, measurement_date),
    ADD CONSTRAINT daily_measurement_station_fk FOREIGN KEY (station_id)
        REFERENCES aemet.station (indicativo);
ALTER TABLE meteo.provincias ADD PRIMARY KEY (postal_code);
ALTER TABLE meteo.station ADD PRIMARY KEY (prov, station_code);
ALTER TABLE meteo.daily_measurement
    ADD CONSTRAINT daily_measurement_station_fk FOREIGN KEY (prov_id, station_id)
        REFERENCES meteo.station (prov, station_code);
CREATE INDEX riaweb_daily_station_date_idx
    ON meteo.daily_measurement (prov_id, station_id, measurement_date);
INSERT INTO meteo.provincias (postal_code, name)
    SELECT id, provincia FROM aemet.provincia;
COMMIT;
